export function resolveLocale(value, browserLanguage = '') {
  const requested = String(value || '').trim().toLowerCase()
  if (requested) return requested.startsWith('zh') ? 'zh' : 'en'
  return String(browserLanguage || '').toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function createTranslator(locale) {
  const dictionary = messages[locale] || messages.en
  return (key, params = {}) => {
    const template = dictionary[key] ?? messages.en[key] ?? key
    return Object.entries(params).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
      template,
    )
  }
}

export function localizedError(locale, reason, serverMessage, fallback) {
  if (locale === 'en') return englishErrors[reason] || fallback
  return serverMessage || fallback
}
